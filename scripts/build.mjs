// Builds base44/functions/askCity/entry.js (one self-contained Base44 backend function)
// from the single source of truth: data/resources.json + src/askcity.mjs.
// data/resources_base44.csv is the Base44 table import and is maintained with the app.
// Run after every catalog change: node scripts/build.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const root = new URL("..", import.meta.url);
const catalog = JSON.parse(readFileSync(new URL("data/resources.json", root), "utf8"));

// ---------- Base44 backend function ----------
// One self-contained file at the path Base44 projects use: base44/functions/askCity/entry.js
const core = readFileSync(new URL("src/askcity.mjs", root), "utf8").replace(/^export /gm, "");
const fn = `// AskMyCity backend function for Base44. GENERATED by scripts/build.mjs.
// Do not edit by hand: change src/askcity.mjs or data/resources.json, run "npm run build", copy this file again.
//
// Secrets (Base44 Dashboard -> Secrets):
//   SWARMS_API_KEY  required for the AI path (ties and questions with no keyword)
//   SWARMS_MODEL    a model from "npm run check:swarms" (gpt-5.4-mini)
//   SWARMS_ENDPOINT optional: swarm | agent | graph (which way to call Swarms first; default swarm)
//   PRUNE_API_KEY   optional; enables the Prune intake step
//   PRUNE_MODEL     optional
//
// Frontend:
//   const { data } = await base44.functions.invoke("askCity", { city: "miami", language: "es", question: "No puedo pagar la renta" });
//   Show data.title, data.summary, data.nextStep, data.source.url, data.source.phone.
//   ({text, lang} also works, and data.card has the same content.)

const CATALOG = ${JSON.stringify(catalog)};

${core}

async function loadSecrets(names) {
  let get = null;
  try {
    const mod = await import("base44:runtime");
    get = (n) => mod.secrets.get(n);
  } catch {
    get = (n) => {
      try { return Deno.env.get(n); } catch { /* not Deno */ }
      try { return process.env[n]; } catch { return undefined; }
    };
  }
  const env = {};
  for (const n of names) {
    try { const v = await get(n); if (v) env[n] = v; } catch { /* missing secret */ }
  }
  return env;
}

const SECRET_NAMES = ["SWARMS_API_KEY", "SWARMS_MODEL", "SWARMS_BASE_URL", "SWARMS_ENDPOINT", "PRUNE_API_KEY", "PRUNE_BASE_URL", "PRUNE_MODEL"];
const CORS = { "Access-Control-Allow-Origin": "*", "Access-Control-Allow-Methods": "POST, OPTIONS", "Access-Control-Allow-Headers": "Content-Type, Authorization" };

export default async function askCityHandler(req) {
  if (req.method === "OPTIONS") return new Response(null, { headers: CORS });
  let body = {};
  try { body = await req.json(); } catch { return Response.json({ error: "send JSON: {city, language, question}" }, { status: 400, headers: CORS }); }
  const env = await loadSecrets(SECRET_NAMES);
  const result = await askCity(body, { catalog: CATALOG, env });
  return Response.json(result, { status: result.error ? 400 : 200, headers: CORS });
}
`;
mkdirSync(new URL("base44/functions/askCity/", root), { recursive: true });
writeFileSync(new URL("base44/functions/askCity/entry.js", root), fn);
console.log(`Built base44/functions/askCity/entry.js (${catalog.length} catalog entries)`);
